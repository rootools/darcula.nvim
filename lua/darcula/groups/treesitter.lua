--- Treesitter captures.
---@param p table palette from `darcula.palette`
---@param opts? darcula.Config
---@return table<string, vim.api.keyset.highlight>
return function(p, opts)
  local comments = opts and opts.styles and opts.styles.comments or {}

  return {
    -- Treesitter
    ["@variable"] = { fg = p.fg },
    ["@variable.builtin"] = { fg = p.self },
    ["@variable.parameter"] = { fg = p.fg },
    ["@variable.member"] = { fg = p.constant },
    ["@property"] = { fg = p.constant },
    ["@constant"] = { fg = p.constant, italic = true },
    ["@constant.builtin"] = { fg = p.keyword },
    ["@module"] = { fg = p.fg },
    ["@label"] = { fg = p.keyword },
    ["@string"] = { fg = p.string },
    ["@string.escape"] = { fg = p.keyword },
    ["@string.special.url"] = { fg = p.link, underline = true },
    ["@character"] = { fg = p.string },
    ["@number"] = { fg = p.number },
    ["@boolean"] = { fg = p.keyword },
    ["@type"] = { fg = p.fg },
    ["@type.builtin"] = { fg = p.keyword },
    ["@type.parameter"] = { fg = p.type_param },
    ["@attribute"] = { fg = p.annotation },
    ["@attribute.builtin"] = { fg = p.annotation },
    ["@function"] = { fg = p.func_decl },
    ["@function.call"] = { fg = p.func_decl },
    ["@function.builtin"] = { fg = p.builtin },
    ["@function.method"] = { fg = p.func_decl },
    ["@function.method.call"] = { fg = p.func_decl },
    ["@constructor"] = { fg = p.fg },
    ["@keyword"] = { fg = p.keyword },
    ["@operator"] = { fg = p.fg },
    ["@punctuation"] = { fg = p.fg },
    ["@punctuation.special"] = { fg = p.keyword },
    ["@comment"] = vim.tbl_extend("force", { fg = p.comment }, comments),
    ["@comment.documentation"] = { fg = p.doc_comment, italic = true },
    ["@comment.error"] = { fg = p.error, bold = true },
    ["@comment.warning"] = { fg = p.warn, bold = true },
    ["@comment.todo"] = { fg = p.todo, bold = true, italic = true },
    ["@comment.note"] = { fg = p.info, bold = true },
    ["@tag"] = { fg = p.tag },
    ["@tag.attribute"] = { fg = p.attr_name },
    ["@tag.delimiter"] = { fg = p.tag },
    ["@markup.strong"] = { bold = true },
    ["@markup.italic"] = { italic = true },
    ["@markup.strikethrough"] = { strikethrough = true },
    ["@markup.underline"] = { underline = true },
    ["@markup.heading"] = { fg = p.keyword, bold = true },
    ["@markup.quote"] = { fg = p.comment, italic = true },
    ["@markup.math"] = { fg = p.number },
    ["@markup.link"] = { fg = p.entity },
    ["@markup.link.label"] = { fg = p.entity },
    ["@markup.link.url"] = { fg = p.link, underline = true },
    ["@markup.raw"] = { fg = p.string },
    ["@markup.list"] = { fg = p.keyword },
    ["@diff.plus"] = { fg = p.git_add },
    ["@diff.minus"] = { fg = p.error },
    ["@diff.delta"] = { fg = p.git_change },
  }
end
